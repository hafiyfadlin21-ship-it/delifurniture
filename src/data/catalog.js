export const formatRM = (n) => {
  const rounded = Math.round(n * 100) / 100;
  const [ringgit, sen] = rounded.toFixed(2).split(".");
  if (sen === "00") return `RM ${Number(ringgit).toLocaleString("en-MY")}`;
  return `RM ${Number(ringgit).toLocaleString("en-MY")}.${sen}`;
};

export const getProduct = (id) => products.find((p) => p.id === id);
export const byCategory = (slug) => products.filter((p) => p.category === slug);
export const byRoom = (slug) => products.filter((p) => p.room === slug);
export const searchProducts = (q) => {
  const s = q.trim().toLowerCase();
  if (!s) return [];
  return products.filter(
    (p) =>
      p.name.toLowerCase().includes(s) ||
      p.type.toLowerCase().includes(s) ||
      p.category.includes(s) ||
      p.description.toLowerCase().includes(s)
  );
};
